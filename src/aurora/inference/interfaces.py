"""Abstract interfaces for inference, model caching, and adapter swapping."""

from abc import ABC, abstractmethod
from typing import Any, Tuple, Iterator
from aurora.models.inference import GenerationResult


class IModelLoader(ABC):
    """Interface managing memory-cached loading of base LLM weights and tokenizers."""

    @abstractmethod
    def load(self, model_name: str, trust_remote_code: bool = False) -> Tuple[Any, Any]:
        """Loads and returns (base_model, tokenizer) once and caches them in memory."""
        pass

    @abstractmethod
    def get_loaded(self) -> Tuple[Any, Any]:
        """Returns the currently cached (base_model, tokenizer). Raises exception if not loaded."""
        pass


class IAdapterManager(ABC):
    """Interface managing dynamic PEFT adapter attachment, switching, and VRAM unloading."""

    @abstractmethod
    def set_adapter(self, model: Any, adapter_path: str, adapter_name: str = "default") -> Any:
        """Attaches or switches to a specific adapter on the provided base model."""
        pass

    @abstractmethod
    def unload_adapter(self, model: Any) -> Any:
        """Detaches all adapters from the model to return it to its raw base state."""
        pass

    @abstractmethod
    def get_current_adapter(self) -> str:
        """Returns the identifier/path of the active adapter, or empty string if none is loaded."""
        pass


class IGenerator(ABC):
    """Interface executing prompt tokenization, causal sequence decoding, and performance stats."""

    @abstractmethod
    def generate(
        self,
        model: Any,
        tokenizer: Any,
        prompt: str,
        temperature: float = 0.7,
        max_new_tokens: int = 512,
        top_p: float = 0.9,
    ) -> GenerationResult:
        """Tokenizes prompt, processes model decoding, and yields a detailed GenerationResult."""
        pass

    @abstractmethod
    def generate_stream(
        self,
        model: Any,
        tokenizer: Any,
        prompt: str,
        temperature: float = 0.7,
        max_new_tokens: int = 512,
        top_p: float = 0.9,
    ) -> Iterator[str]:
        """Yields text chunks dynamically as they are generated by the model."""
        pass


class IInferenceEngine(ABC):
    """Orchestrator coordinating loader, adapter manager, and generator components."""

    @abstractmethod
    def initialize(self, model_name: str, trust_remote_code: bool = False) -> None:
        """Pre-loads the base model and tokenizer in memory."""
        pass

    @abstractmethod
    def generate(
        self,
        prompt: str,
        adapter_path: str = "",
        temperature: float = 0.7,
        max_new_tokens: int = 512,
        top_p: float = 0.9,
    ) -> GenerationResult:
        """Swaps adapters dynamically and runs response generation."""
        pass

    @abstractmethod
    def generate_stream(
        self,
        prompt: str,
        adapter_path: str = "",
        temperature: float = 0.7,
        max_new_tokens: int = 512,
        top_p: float = 0.9,
    ) -> Iterator[str]:
        """Swaps adapters dynamically and yields text chunks in real-time."""
        pass
